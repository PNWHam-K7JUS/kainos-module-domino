        // the bits read as a binary number (a code always starts with 1, so that's unique) -> the byte
        private static readonly Dictionary<int, int> Decode = build();

        private static Dictionary<int, int> build()
        {
            Dictionary<int, int> d = new Dictionary<int, int>();
            for (int i = 0; i < Codes.Length; i++)
            {
                int v = 0;
                foreach (char c in Codes[i]) v = (v << 1) | (c == '1' ? 1 : 0);
                d[v] = i;
            }
            return d;
        }

        // the byte for a code's bits (-1: none)
        public static int Lookup(int bits)
        {
            int b;
            return Decode.TryGetValue(bits, out b) ? b : -1;
        }
