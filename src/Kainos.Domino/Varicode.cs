    // Received bits to text: a character ends at "00"; UTF-8 put back together; CR LF to a new line
    internal sealed class VaricodeReader
    {
        private int _shreg;
        private readonly List<byte> _utf8 = new List<byte>();
        private int _utf8Need;
        private bool _lastCr;

        // returns the text that's complete (or null)
        public string Bit(int bit)
        {
            _shreg = (_shreg << 1) | (bit & 1);
            if ((_shreg & 3) != 0)
            {
                if (_shreg > 0x3fffff) _shreg &= 0x3fffff;      // a run without a gap: noise
                return null;
            }
            int code = _shreg >> 2;
            _shreg = 0;
            if (code == 0) return null;                         // idle
            int b = Varicode.Lookup(code);
            return b < 0 ? null : Byte(b);
        }

        public string Byte(int b)
        {
            if (b >= 0x80)
            {
                if ((b & 0xc0) == 0x80 && _utf8Need > 0)
                {
                    _utf8.Add((byte)b);
                    if (--_utf8Need > 0) return null;
                    string s = System.Text.Encoding.UTF8.GetString(_utf8.ToArray());
                    _utf8.Clear();
                    return s;
                }
                _utf8.Clear();
                int need = (b & 0xe0) == 0xc0 ? 1 : (b & 0xf0) == 0xe0 ? 2 : (b & 0xf8) == 0xf0 ? 3 : 0;
                if (need == 0) { _utf8Need = 0; return ((char)b).ToString(); }      // Latin-1, from an older program
                _utf8.Add((byte)b);
                _utf8Need = need;
                return null;
            }
            if (_utf8Need > 0) { _utf8Need = 0; _utf8.Clear(); }
            bool cr = _lastCr;
            _lastCr = b == 13;
            if (b == 13) return "\n";
            if (b == 10) return cr ? null : "\n";
            if (b == 8) return "\b";
            if (b == 9) return " ";
            if (b < 32 || b == 127) return null;
            return ((char)b).ToString();
        }
    }
